"""Demo-state wipe — Phase 22.

Single function ``wipe_everything()`` that nukes ALL workflow-driving data
across Snowflake + PostgreSQL + SQL Server in one transaction-like sequence,
returning a structured report the UI can render.

What it WIPES (workflow data):
  * Snowflake CONTROL.* — every table that drives the pipeline workflow:
      - global_bronze_catalog_datasets + fields (the 33-dataset seed)
      - global_silver_schema_* (datasets + tables + columns)
      - global_gold_schema_* (datasets + fields)
      - all *_mappings, *_audit_log, client_*, pipeline_*, dq_*, gx_*,
        agent_proposals, version_history, schema_drift_events …
  * Snowflake per-client schemas — BRONZE_<client> / SILVER_<client> /
    GOLD_<client> dropped CASCADE
  * PostgreSQL operational DB — all data tables in the configured database
  * SQL Server operational DB — same
  * Filesystem — auto-generated DAG factories, dbt models, DDL files,
    generated data files
  * Airflow metadata — task_instance / dag_run / xcom / log

What it KEEPS (infrastructure):
  * Snowflake account, warehouse, role, database (DATALINK_DEV), CONTROL
    schema definition (tables empty but exist)
  * The 6 industry-standard RAG chunks in standard_registry (10 min to
    reload via Voyage; user can flag `--include-standards` to drop them
    too)
  * Postgres / SQL Server / Airflow infra containers (still running)
  * .env, API keys, dbt profiles
  * Docker compose stack

This is "factory reset to pre-`load_product_catalog` state" — exactly what
the user described as "nothing that drives workflow is concerned".
"""

