def wipe_everything(
    *,
    actor: str,
    include_standards: bool = False,
    include_airflow: bool = True,
    include_files: bool = True,
) -> WipeReport:
    """Wipe all workflow-driving data across Snowflake + Postgres + SQL Server.

    Demo lifecycle: call this between demos to start from a clean slate
    with zero datasets, zero designs, zero instances, zero DQ runs.

    Args:
        actor: who triggered (e.g. ``"admin:ui:jatin"``) — logged.
        include_standards: if True, also wipes the 6 industry-standards
            (FHIR/X12/NCPDP/CMS/DV2/HEDIS).  These take ~10 min to reload
            via Voyage so default is False.
        include_airflow: wipe Airflow metadata DB (task_instance / dag_run).
        include_files: remove auto-generated DAG factories + dbt + DDL files.
    """
    rpt = WipeReport(actor=actor, started_at=_now())

    # Snowflake — the main event
    rpt.sections["snowflake"] = _wipe_snowflake(actor=actor)

    # Standards opt-in
    if include_standards:
        try:
            _wh().execute(f"DELETE FROM {CONTROL_SCHEMA}.standard_chunks")
            _wh().execute(f"DELETE FROM {CONTROL_SCHEMA}.standard_registry")
            rpt.sections["snowflake"]["counts"]["tables"] += 2
            rpt.sections["snowflake"]["counts"]["standards_wiped"] = 1
        except Exception as exc:
            rpt.sections["snowflake"]["warnings"].append(f"standards wipe: {str(exc)[:120]}")

    # Postgres
    rpt.sections["postgres"] = _wipe_postgres(actor=actor)

    # SQL Server (warnings-only if container down)
    rpt.sections["sqlserver"] = _wipe_sqlserver(actor=actor)

    # Filesystem
    if include_files:
        rpt.sections["files"] = _wipe_generated_files(actor=actor)

    # Airflow
    if include_airflow:
        rpt.sections["airflow"] = _wipe_airflow(actor=actor)

    rpt.finished_at = _now()

    # Audit log — reuse the per-op pattern, log under a synthetic ResetReport
    try:
        from datalink.admin.reset import ResetReport

        synth = ResetReport(
            operation="wipe_everything",
            actor=actor,
            started_at=rpt.started_at,
            finished_at=rpt.finished_at,
            counts=rpt.total_counts(),
            warnings=[w for s in rpt.sections.values() for w in s.get("warnings", [])],
            errors=[e for s in rpt.sections.values() for e in s.get("errors", [])],
        )
        _log_audit(synth, None)
    except Exception as exc:
        _log.warning("wipe_everything.audit_log_failed", err=str(exc)[:200])

    # Final sweep: the audit-log itself was wiped during _wipe_snowflake,
    # but the helpers above (`reset_airflow_metadata` → `_log_audit` and our
    # own synthetic `_log_audit` call) each append a row.  For "from scratch
    # for team to comprehend" demos the operator wants a TRULY pristine
    # admin_reset_audit_log too — so we truncate AFTER all the audit writers
    # have run.  Cost: lose the in-this-call audit trail.  Worth it for
    # repeatable demo state.
    try:
        _wh().execute(f"DELETE FROM {CONTROL_SCHEMA}.admin_reset_audit_log")
    except Exception as exc:
        _log.warning("wipe_everything.final_audit_truncate_failed", err=str(exc)[:200])

    return rpt
